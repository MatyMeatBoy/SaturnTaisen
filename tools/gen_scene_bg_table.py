"""Write the compiled-in table the runtime uses to recognise a scene picture (T74).

Usage: python tools/gen_scene_bg_table.py config/hd-scene-bg-map.json OUT_HEADER.h

Only pairs that are safe to draw are kept: tier `content` (the same-number PC picture is the best of all PC
pictures) or a tier-`number` pair confirmed by eye in config/hd-scene-bg-review.json, a 288x144 Saturn picture
that is a full picture (BG3xxx/BG4xxx are character cut-outs on a key colour and BG0000 is blank) and not listed
as rejected, and a palette fingerprint that identifies one PC picture (a palette shared by pictures that map to
different PC files is skipped). The fingerprint is the FNV-1a hash of the 256 colour-RAM
words the game loads for the picture, the same value `Renderer::BackgroundPaletteFingerprint` computes.
"""
import json
import sys
from pathlib import Path


def main():
    data = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
    review = json.loads((Path(sys.argv[1]).parent / 'hd-scene-bg-review.json').read_text(encoding='utf-8'))
    confirmed, rejected = set(review['eye_confirmed_number_tier']), set(review['rejected'])
    by_palette, by_palette_content = {}, {}
    for pair in data['pairs']:
        name = pair['saturn_file'].split('/')[-1][:-4]
        if pair.get('size') != [288, 144] or not pair['saturn_file'].startswith('SAKURA1/'):
            continue
        if name[2:3] in '34' or name in rejected or name == 'BG0000':
            continue
        if not (pair.get('tier') == 'content' or (pair.get('tier') == 'number' and name in confirmed)):
            continue
        key = (pair['pc_file'], pair['pc_image_index'])
        by_palette.setdefault(pair['palette_fnv'], set()).add(key)
        if pair['tier'] == 'content':
            by_palette_content.setdefault(pair['palette_fnv'], set()).add(key)
    # A palette shared by pictures that map to different PC files cannot identify one of them, unless the
    # content-backed pairs among them agree on a single PC file (they outrank eye-confirmed number pairs).
    rows = []
    for palette, keys in by_palette.items():
        if len(keys) != 1:
            keys = by_palette_content.get(palette, keys)
        if len(keys) == 1:
            rows.append((palette, next(iter(keys))))
    rows.sort()
    lines = ['// Generated by tools/gen_scene_bg_table.py from config/hd-scene-bg-map.json. Do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace port {',
             'struct SceneBgEntry {uint64_t palette;const char* file;unsigned index;};',
             'inline constexpr SceneBgEntry kSceneBg[]={']
    lines += ['    {0x%sull,"%s",%d},' % (k, f, i) for k, (f, i) in rows]
    lines += ['};', 'inline constexpr unsigned kSceneBgCount=sizeof(kSceneBg)/sizeof(kSceneBg[0]);', '}']
    Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(len(rows), 'entries')


if __name__ == '__main__':
    main()
