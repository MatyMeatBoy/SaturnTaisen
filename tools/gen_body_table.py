"""Write the compiled-in table the runtime uses to recognise a large character body (T19).

  python tools/gen_body_table.py "local/prepared/disc1/Track 01.iso" OUT_HEADER.h

A body on screen is one VDP1 texture whose bytes equal the bitmap of its NC*.BIN (8 bpp, `stride` x 144, from
0x610). The table holds the FNV-1a 64 hash of that bitmap, the disc file name and the PC picture file, for the
bodies that `tools/match_hd_bodies.py` paired and `config/hd-body-review.json` did not reject. Hashes and names
only; no pixels. A hash shared by two files is skipped.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import decode_saturn_bg as saturn  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def fnv(data):
    value = 14695981039346656037
    for byte in data:
        value = ((value ^ byte) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return value


def main():
    body_map = json.loads((ROOT / 'config/hd-body-map.json').read_text(encoding='utf-8'))
    review = json.loads((ROOT / 'config/hd-body-review.json').read_text(encoding='utf-8'))
    confirmed, rejected = set(review['eye_confirmed_candidates']), set(review['rejected'])
    iso = saturn.Iso(sys.argv[1])
    files = dict(iso.files('SAKURA1'))
    rows, seen = [], {}
    for pair in body_map['pairs']:
        name = pair['saturn_file'].split('/')[-1][:-4]
        if name in rejected or not (pair['tier'] == 'content' or name in confirmed):
            continue
        data = iso.content(files[name + '.BIN'])
        stride = saturn.nc_stride(data)
        digest = fnv(data[0x610:0x610 + stride * 144])
        seen.setdefault(digest, []).append(name)
        rows.append((digest, name, stride))
    rows = [r for r in rows if len(seen[r[0]]) == 1]
    rows.sort(key=lambda r: r[1])
    lines = ['// Generated by tools/gen_body_table.py from config/hd-body-map.json. Do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace port {',
             'struct BodyEntry {uint64_t hash;const char* disc;const char* pc;unsigned stride;};',
             'inline constexpr BodyEntry kBodies[]={']
    lines += ['    {0x%016Xull,"%s.BIN","SAKURA1/NC/%s.SPR",%d},' % (h, n, n, w) for h, n, w in rows]
    lines += ['};', 'inline constexpr unsigned kBodyCount=sizeof(kBodies)/sizeof(kBodies[0]);', '}']
    Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(len(rows), 'bodies')


if __name__ == '__main__':
    main()
