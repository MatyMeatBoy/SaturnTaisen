"""Write the compiled-in tables for EVE pictures and scrolling pictures (T105).

Usage: python tools/gen_eve_bg_table.py config/hd-eve-bg-map.json OUT_HEADER.h

kEveBg holds only the enabled EVE pictures (palette fingerprint of layer 5 -> PC picture and crop window); kScrollBg lists
the scrolling pictures the runtime may report but never draws (their palette can be shared, e.g. BG2247 and BG2252).
"""
import json
import sys
from pathlib import Path


def render(data):
    eve = [e for e in data['eve'] if e['enabled']]
    for e in eve:
        x, y, w, h = e['window']
        assert w > 0 and h > 0, e['eve']
    palettes = [e['palette'] for e in eve]
    assert len(palettes) == len(set(palettes)), 'duplicate EVE palette'
    # One row per palette; an EVE seen on both discs has the same bytes, hence one row.
    lines = ['// Generated by tools/gen_eve_bg_table.py from config/hd-eve-bg-map.json. Do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace port {',
             'struct EveBgEntry {uint64_t palette;const char* file;unsigned index;int window[4];const char* name;};',
             'inline constexpr EveBgEntry kEveBg[]={']
    lines += ['    {0x%sull,"%s",%d,{%d,%d,%d,%d},"%s"},' % (e['palette'], e['pc_file'], e['pc_image_index'], *e['window'], e['eve'])
              for e in sorted(eve, key=lambda e: e['palette'])]
    lines += ['};', 'inline constexpr unsigned kEveBgCount=sizeof(kEveBg)/sizeof(kEveBg[0]);',
              'struct ScrollBgEntry {uint64_t palette;const char* file;bool wide;};',
              'inline constexpr ScrollBgEntry kScrollBg[]={']
    lines += ['    {0x%sull,"%s",%s},' % (s['palette'], s['file'].split('/')[-1][:-4], 'true' if s['class'] == 'wide_scroll' else 'false')
              for s in data['scroll']]
    lines += ['};', 'inline constexpr unsigned kScrollBgCount=sizeof(kScrollBg)/sizeof(kScrollBg[0]);', '}']
    return '\n'.join(lines) + '\n', len(eve), len(data['scroll'])


def main():
    text, a, b = render(json.loads(Path(sys.argv[1]).read_text(encoding='utf-8')))
    Path(sys.argv[2]).write_text(text, encoding='utf-8')
    print(a, 'EVE entries,', b, 'scroll entries')


if __name__ == '__main__':
    main()
