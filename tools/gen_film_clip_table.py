"""T113/S3: turns config/film-fad-map.json into the C++ table the runtime uses to pick the PC clip of a Saturn film.

Key = (disc 1 or 2, a start FAD inside [fad, fad + sectors) of the stream). Alternate cuts (a different edit of the scene) are left out: the Saturn
picture stays for them. Output: a header for local/deps/satrecomp/port/film_clip_table.h (carried by a numbered patch).
"""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
data = json.load(open(ROOT / 'config/film-fad-map.json', encoding='utf8'))
# Every stream is listed (a play command may start anywhere inside one: the game re-issues it at later sectors); movie is -1 for the
# alternate cuts and the unpaired ones, which keep the Saturn picture.
rows = sorted({(s['disc'], s['fad'], s['sectors'],
                int(s['movie'][5:]) if s.get('movie', '').startswith('MOVIE') and not s.get('alternate_cut') else -1)
               for s in data['streams']})
out = ['// SPDX-License-Identifier: GPL-3.0-only', '// Generated by tools/gen_film_clip_table.py from config/film-fad-map.json: do not edit.',
       '#pragma once', '#include <cstdint>', 'namespace port {', 'struct FilmClip {uint8_t disc;uint32_t fad;uint32_t sectors;int16_t movie;};',
       f'inline constexpr FilmClip kFilmClips[{len(rows)}]={{']
out += [f'    {{{d},0x{f:X},{n},{m}}},' for d, f, n, m in rows]
out += ['};', f'inline constexpr unsigned kFilmClipCount={len(rows)};', '}']
text = '\n'.join(out) + '\n'
target = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'local/deps/satrecomp/port/film_clip_table.h'
target.write_text(text, encoding='utf8', newline='\n'); print(len(rows), 'clips ->', target)
