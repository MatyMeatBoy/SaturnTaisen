"""Write the recognition table for the remaining SYSTEM/WALL menu and HUD pictures (T110, after T102/T108).

Usage: python tools/gen_system_hud_table.py config/hd-system-hud-review.json OUT_HEADER.h
       python tools/gen_system_hud_table.py config/hd-system-hud-review.json --verify
           [--iso "local/prepared/disc1/Track 01.iso"] [--pc-root local/work/pc-cab/out]

Same idea as T74/T108 (palette fingerprint -> PC picture) applied to the T110 review:
  * `conditional_candidate` (FONT_CSL) -> kSystemHud, one row per saved VDP1 command: the key is the SHA-256 of the
    8x16 texture bytes plus the SHA-256 of the 16 CRAM words (the palette identity); `enabled` is always 0 until
    T110a proves anchors, selected/disabled palettes and interpolation at runtime.
  * the WALL1 pair (`existing_backdrop_provenance`) -> kSystemHud with the 64-bit FNV-1a palette fingerprint; the
    generated backdrop path already draws it, so this is provenance, not a new substitution.
  * everything else (keep_native, no_native_witness, needs_layout, existing_portrait_source) -> kSystemHudPending
    with the reason; none has a recognisable native texture offline, so they need runtime evidence (T109/T110a).
Output is deterministic. `--verify` reads private data read-only and prints only match/mismatch.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

CONDITIONAL = 'conditional_candidate'
PENDING_REASON = {
    'no_native_witness': 'needs_runtime_witness',
    'needs_layout': 'needs_runtime_layout',
    'keep_native': 'keep_native',
    'existing_portrait_source': 'existing_route',
}


def build(review):
    """Return (rows, pending): rows are dicts for kSystemHud, pending are (id, status, reason)."""
    rows, pending = [], []
    for item in review['system']:
        if item['status'] == CONDITIONAL:
            for ev in sorted(item['saved_command_evidence'], key=lambda e: e['pc_index']):
                rows.append({'kind': 'command', 'file': item['pc_path'], 'index': ev['pc_index'],
                             'pc_sha256': item['pc_sha256'], 'width': ev['size'][0], 'height': ev['size'][1],
                             'texture': ev['texture_sha256'], 'cram': ev['cram_sha256'],
                             'mode': ev['cmd_mode'], 'color': ev['cmd_color'], 'enabled': 0})
        else:
            pending.append((item['id'], item['status'], PENDING_REASON.get(item['status'], 'needs_runtime_witness')))
    wall = review.get('wall')
    if wall and wall.get('status') == 'existing_backdrop_provenance':
        rows.append({'kind': 'palette', 'file': wall['pc_file'], 'index': wall['pc_index'], 'pc_sha256': wall['pc_sha256'],
                     'width': wall['saturn_size'][0], 'height': wall['saturn_size'][1],
                     'palette': wall['palette_fnv'].upper(), 'enabled': 0})
    return rows, sorted(pending)


def render(rows, pending):
    out = ['// Generated by tools/gen_system_hud_table.py from config/hd-system-hud-review.json. Do not edit.',
           '#pragma once', '#include <cstdint>', 'namespace port {',
           'struct SystemHudEntry {uint64_t palette;const char* texture_sha256;const char* cram_sha256;const char* file;'
           'unsigned index;unsigned width;unsigned height;uint8_t enabled;};',
           'struct SystemHudPending {const char* id;const char* status;const char* reason;};',
           'inline constexpr SystemHudEntry kSystemHud[]={']
    for r in rows:
        out.append('    {0x%sull,"%s","%s","%s",%d,%d,%d,%d},' % (
            r.get('palette', '0' * 16), r.get('texture', ''), r.get('cram', ''), r['file'], r['index'],
            r['width'], r['height'], r['enabled']))
    out += ['};', 'inline constexpr unsigned kSystemHudCount=sizeof(kSystemHud)/sizeof(kSystemHud[0]);',
            'inline constexpr SystemHudPending kSystemHudPending[]={']
    out += ['    {"%s","%s","%s"},' % p for p in pending]
    out += ['};', 'inline constexpr unsigned kSystemHudPendingCount=sizeof(kSystemHudPending)/sizeof(kSystemHudPending[0]);', '}']
    return '\n'.join(out) + '\n'


def verify(review, iso_path=None, pc_root=None):
    """Compare the review with private data, read-only. Returns {check: True/False/None (data absent)}."""
    results = {}
    wall = review['wall']
    if iso_path and Path(iso_path).is_file():
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import decode_saturn_bg as saturn
        iso = saturn.Iso(iso_path)
        data = next((iso.content(e) for n, e in iso.files('SAKURA1') if n == 'WALL1.BIN'), None)
        results['wall1_sha256'] = None if data is None else hashlib.sha256(data).hexdigest() == wall['saturn_sha256']
        results['wall1_palette_fnv'] = None if data is None else \
            saturn.palette_fingerprint(data) == int(wall['palette_fnv'], 16)
    else:
        results['wall1_sha256'] = results['wall1_palette_fnv'] = None
    pcs = [(wall['pc_file'], wall['pc_sha256'])] + [(i['pc_path'], i['pc_sha256']) for i in review['system']]
    for rel, expected in pcs:
        path = Path(pc_root) / rel if pc_root else None
        results['pc:' + rel] = hashlib.sha256(path.read_bytes()).hexdigest() == expected \
            if path and path.is_file() else None
    return results


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('review', type=Path)
    ap.add_argument('out', nargs='?', type=Path)
    ap.add_argument('--verify', action='store_true')
    ap.add_argument('--iso')
    ap.add_argument('--pc-root')
    args = ap.parse_args()
    review = json.loads(args.review.read_text(encoding='utf-8'))
    if args.verify:
        results = verify(review, args.iso, args.pc_root)
        for key, value in sorted(results.items()):
            print(key, {True: 'match', False: 'MISMATCH', None: 'data absent'}[value])
        return 1 if any(v is False for v in results.values()) else 0
    rows, pending = build(review)
    args.out.write_text(render(rows, pending), encoding='utf-8')
    print(len(rows), 'entries,', len(pending), 'pending runtime/keep-native')
    return 0


if __name__ == '__main__':
    sys.exit(main())
