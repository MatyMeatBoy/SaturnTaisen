#!/usr/bin/env python3
"""Derive the full-frame table (config/hd-full-frames.json and port/full_frame_rows.h) offline (TP2b).

A full-frame row is a Saturn picture the VDP2 shows as the whole 320x224 frame (the six disc 2 portrait cards BBG238-BBG243
and the gradient BBG300). The PC art is not that frame at 2x: it is drawn wider, so each row carries the PC crop box that
tools/measure_size_candidates.py measured (config/hd-size-candidates.json, grayscale signature floor 0.90). The runtime draws
that crop stretched over the whole 320x224 frame when, and only when, the frame is exactly the Saturn picture (palette,
one winning layer over every pixel and the RGB hash of the whole frame), and keeps the native frame otherwise.

Only names, hashes and dimensions are written (no pixels). `build_rows` and `render_header` are pure and unit tested
(tests/test_gen_full_frame_rows.py); `main` needs the prepared discs and the extracted PC files.
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))

FRAME = (320, 224)
MIN_CORRELATION = 0.90
# The measured box may stretch the frame; a box this far from the Saturn aspect is not the same picture.
MAX_ASPECT_DRIFT = 0.20
MIN_BOX_SHARE = 0.5  # smallest share of the PC picture a crop may cover on either axis


def fnv(raw):
    h = 0xcbf29ce484222325
    for b in raw:
        h = ((h ^ b) * 1099511628211) & 0xffffffffffffffff
    return h


def rgb_hash(rgb_bytes):
    """FNV-1a over R, G, B of every pixel, 5-bit channels widened by <<3: what the runtime's insetRgb hashes for the frame."""
    return fnv(rgb_bytes)


def saturn_frame_bytes(image):
    """RGB bytes of a decoded Saturn picture as the VDP2 renderer shows it (5-bit channel << 3, no replication)."""
    return bytes((round(c * 31 / 255) << 3) & 0xff for c in image.convert('RGB').tobytes())


def crop_from_box(box, pc_size):
    """Candidate box (x0, y0, x1, y1) -> runtime crop {x, y, w, h}; reject a box outside the picture or too small."""
    x0, y0, x1, y1 = box
    pw, ph = pc_size
    if not (0 <= x0 < x1 <= pw and 0 <= y0 < y1 <= ph):
        raise ValueError(f'crop box {tuple(box)} leaves the {pw}x{ph} PC picture')
    w, h = x1 - x0, y1 - y0
    if w < pw * MIN_BOX_SHARE or h < ph * MIN_BOX_SHARE:
        raise ValueError(f'crop box {tuple(box)} covers too little of the PC picture')
    drift = abs((w / h) / (FRAME[0] / FRAME[1]) - 1)
    if drift > MAX_ASPECT_DRIFT:
        raise ValueError(f'crop box {tuple(box)} aspect drifts {drift:.2f} from the Saturn frame')
    return {'x': x0, 'y': y0, 'w': w, 'h': h}


def build_rows(candidates, resolve):
    """candidates: config/hd-size-candidates.json. resolve(name) -> dict with disc, native_bytes, native_fnv, palette, rgb,
    pc_file, pc_bytes, pc_fnv, pc_size (None when the picture is not on the prepared discs).
    Returns (rows, skipped). Palette keys must be unique among rows: a shared palette cannot identify a picture."""
    rows, skipped = [], {}
    for name in sorted(candidates):
        c = candidates[name]
        if not name.startswith('BBG') or c.get('native') != list(FRAME):
            continue
        if not c.get('passes_floor') or c.get('min', 0) < MIN_CORRELATION:
            skipped[name] = f"measured crop correlation {c.get('min')} is below the {MIN_CORRELATION} floor"
            continue
        boxes = c.get('best_boxes') or []
        if len(boxes) != 1:
            skipped[name] = 'no single measured crop box'
            continue
        info = resolve(name)
        if info is None:
            skipped[name] = 'not on the prepared discs or PC files missing'
            continue
        if list(info['pc_size']) != c['pc']:
            skipped[name] = 'PC picture size differs from the measured one'
            continue
        try:
            crop = crop_from_box(boxes[0], tuple(info['pc_size']))
        except ValueError as error:
            skipped[name] = str(error)
            continue
        rows.append({'name': name, 'disc': info['disc'], 'native_bytes': info['native_bytes'],
                     'native_fnv': info['native_fnv'], 'palette': info['palette'], 'rgb': info['rgb'],
                     'pc_file': info['pc_file'], 'pc_bytes': info['pc_bytes'], 'pc_fnv': info['pc_fnv'],
                     'pc_width': info['pc_size'][0], 'pc_height': info['pc_size'][1], 'crop': crop,
                     'min_crop_correlation': c['min']})
    count = {}
    for r in rows:
        count[r['palette']] = count.get(r['palette'], 0) + 1
    shared = [r['name'] for r in rows if count[r['palette']] > 1]
    for name in shared:
        skipped[name] = 'palette shared with another full-frame row'
    return [r for r in rows if r['name'] not in shared], skipped


def render_header(rows):
    lines = ['// Generated by tools/gen_full_frame_rows.py from config/hd-full-frames.json. Do not edit by hand.',
             '// name, VDP2 palette key, RGB hash of the whole native 320x224 frame, PC file/bytes/fnv, PC w x h, PC crop x, y, w, h']
    for r in rows:
        c = r['crop']
        lines.append('{"%s", 0x%sull, 0x%sull, "%s", %d, 0x%sull, %d, %d, {%d, %d, %d, %d}},' % (
            r['name'], r['palette'], r['rgb'], r['pc_file'], r['pc_bytes'], r['pc_fnv'], r['pc_width'], r['pc_height'],
            c['x'], c['y'], c['w'], c['h']))
    return '\n'.join(lines) + '\n'


def main():
    from decode_saturn_bg import Iso, decode, palette_fingerprint
    from decode_spred import decode as decode_pc
    ap = argparse.ArgumentParser()
    ap.add_argument('--prepared', default=str(ROOT / 'local/prepared'))
    ap.add_argument('--pc', required=True, help='PC game root holding SAKURA2/BG')
    ap.add_argument('--candidates', default=str(ROOT / 'config/hd-size-candidates.json'))
    ap.add_argument('--header', help='write the C++ rows (port/full_frame_rows.h)')
    ap.add_argument('--out', default=str(ROOT / 'config/hd-full-frames.json'))
    a = ap.parse_args()
    candidates = json.loads(Path(a.candidates).read_text(encoding='utf-8'))
    disc2 = Iso(str(Path(a.prepared) / 'disc2' / 'Track 01.iso'))

    def resolve(name):
        entry = disc2.find(f'/SAKURA2/{name}.BIN')
        if not entry:
            return None
        raw = disc2.content(entry)
        pc_path = Path(a.pc) / 'SAKURA2' / 'BG' / f'{name}.SPR'
        if not pc_path.exists():
            return None
        pc = pc_path.read_bytes()
        image = decode(raw)
        if image is None or image.size != FRAME:
            return None
        return {'disc': 2, 'native_bytes': len(raw), 'native_fnv': f'{fnv(raw):016X}',
                'palette': f'{palette_fingerprint(raw):016X}', 'rgb': f'{rgb_hash(saturn_frame_bytes(image)):016X}',
                'pc_file': f'SAKURA2/BG/{name}.SPR', 'pc_bytes': len(pc), 'pc_fnv': f'{fnv(pc):016X}',
                'pc_size': list(dict(decode_pc(pc))[0].size)}

    rows, skipped = build_rows(candidates, resolve)
    Path(a.out).write_text(json.dumps({'frame': list(FRAME), 'rows': rows, 'skipped': skipped}, indent=1) + '\n',
                           encoding='utf-8', newline='\n')
    if a.header:
        Path(a.header).write_text(render_header(rows), encoding='utf-8', newline='\n')
    for r in rows:
        print(r['name'], r['crop'], r['min_crop_correlation'])
    for k, v in skipped.items():
        print('skip', k, v)


if __name__ == '__main__':
    main()
