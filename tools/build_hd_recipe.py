"""Regenerate config/hd-portrait-recipe.json, the list the release uses to rebuild the HD portrait pack.

  python tools/build_hd_recipe.py            rewrite the recipe
  python tools/build_hd_recipe.py --check    fail if the tracked recipe is behind the approved matches

Every portrait the HD mod replaces must be in the recipe, or a release would silently ship fewer
portraits than the project has approved. Sources:

  config/hd-portrait-reviewed.json                 the reviewed matches (tracked)
  local/work/hd-matcher-project/project.json       the owner's matcher project: the automatic exact matches

The recipe holds identifiers, offsets and hashes only (no pixels, no paths). tools/taisen_setup.py reads it
on the player's PC, takes the Saturn identities from their discs and the PC sheets from their PC edition,
and skips any row whose hashes do not match, so a wrong row can only fall back to the Saturn portrait.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RECIPE = ROOT / 'config/hd-portrait-recipe.json'
NOTE = ('Which PC portrait sheet replaces each Saturn portrait identity: identifiers, offsets and hashes only. '
        'Generated by tools/build_hd_recipe.py from the reviewed matches (config/hd-portrait-reviewed.json) plus '
        "the automatic exact matches; tools/taisen_setup.py rebuilds the pack from the player's own files.")


def build(project: dict, reviewed: dict) -> dict:
    approved = {match['id']: match for match in reviewed['matches']}
    rows = []
    for row in project['rows']:
        match = approved.pop(row['id'], None)
        if match:
            if row['raw_sha256'] != match['native_raw_sha256']:
                raise ValueError(f"{row['id']}: reviewed identity differs from the project")
            recipe_row = dict(id=row['id'], pc_index=match['pc_index'], dx=match['dx'], dy=match['dy'],
                              native_raw_sha256=match['native_raw_sha256'],
                              variants_rgba_sha256=match['variants_rgba_sha256'])
            swap_strips = match.get('swap_strips', False)
            if type(swap_strips) is not bool:
                raise ValueError(f"{row['id']}: invalid strip swap")
            if swap_strips:
                recipe_row['swap_strips'] = True
            rows.append(recipe_row)
        elif row['status'] in ('auto', 'accepted'):
            rows.append(dict(id=row['id'], pc_index=row['selected'], dx=row['dx'], dy=row['dy'],
                             native_raw_sha256=row['raw_sha256']))
    if approved:
        raise ValueError('reviewed identities missing from the project: ' + ', '.join(sorted(approved)))
    source = {key: reviewed['source'][key] for key in ('bytes', 'sha256', 'fnv64')}
    if any(project['source'][key] != value for key, value in source.items()):
        raise ValueError('the project and the reviewed matches use different portrait archives')
    return dict(schema=1, note=NOTE, source=source, palette_hash=project['palette_hash'], portraits=rows)


def main() -> int:
    owner = Path(os.environ.get('SAKURA_OWNER_ROOT', ROOT))
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--project', type=Path, default=owner / 'local/work/hd-matcher-project/project.json')
    parser.add_argument('--reviewed', type=Path, default=ROOT / 'config/hd-portrait-reviewed.json')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    recipe = build(json.loads(args.project.read_text(encoding='utf-8')),
                   json.loads(args.reviewed.read_text(encoding='utf-8')))
    text = json.dumps(recipe, indent=1) + '\n'
    if args.check:
        if not RECIPE.is_file() or RECIPE.read_text(encoding='utf-8') != text:
            print('config/hd-portrait-recipe.json is behind the approved matches; run tools/build_hd_recipe.py')
            return 1
        print(f'recipe up to date: {len(recipe["portraits"])} portraits')
        return 0
    RECIPE.write_text(text, encoding='utf-8', newline='\n')
    print(f'{RECIPE.relative_to(ROOT)}: {len(recipe["portraits"])} portraits')
    return 0


if __name__ == '__main__':
    sys.exit(main())
