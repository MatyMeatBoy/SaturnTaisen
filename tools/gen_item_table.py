"""Write the compiled-in table the runtime will use to recognise an item picture (T102, from T23/T54).

Usage: python tools/gen_item_table.py config/hd-item-map.json OUT_HEADER.h

Same pattern as tools/gen_scene_bg_table.py (T74): the key is the FNV-1a palette fingerprint of the
ITEMnn.BIN picture (112x112, 8 bpp, palette first). Tier `content` pairs and the exact full-card matches confirmed in hd-item-review.json are kept. A palette that maps
to different PC pictures cannot identify one and is skipped. Output is deterministic (sorted by palette).
Not wired into the runtime yet: VDP1 sprite recognition is a separate row.
"""
import json
import sys
from pathlib import Path


def review_key(pair):
    return pair['saturn_file'], pair['pc_file'], pair['pc_image_index'], pair['pc_sha256']


def build_rows(data, review=()):
    confirmed = {review_key(pair) for pair in review if pair['verdict'] == 'confirmed'}
    by_palette = {}
    for pair in data['pairs']:
        tier = pair.get('tier')
        if tier == 'candidate' and (not confirmed or review_key(pair) not in confirmed):
            continue
        if tier not in ('content', 'candidate'):
            continue
        key = (pair['pc_file'], pair['pc_image_index'])
        by_palette.setdefault(pair['palette_fnv'].upper(), set()).add(key)
    return sorted((p, next(iter(k))) for p, k in by_palette.items() if len(k) == 1)


def render(rows):
    lines = ['// Generated by tools/gen_item_table.py from the item map and visual review. Do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace port {',
             'struct ItemEntry {uint64_t palette;const char* file;unsigned index;};',
             'inline constexpr ItemEntry kItem[]={']
    lines += ['    {0x%sull,"%s",%d},' % (p, f, i) for p, (f, i) in rows]
    lines += ['};', 'inline constexpr unsigned kItemCount=sizeof(kItem)/sizeof(kItem[0]);', '}']
    return '\n'.join(lines) + '\n'


def main():
    map_path = Path(sys.argv[1])
    data = json.loads(map_path.read_text(encoding='utf-8'))
    review_path = map_path.with_name('hd-item-review.json')
    review = json.loads(review_path.read_text(encoding='utf-8'))['pairs'] if review_path.is_file() else ()
    rows = build_rows(data, review)
    Path(sys.argv[2]).write_text(render(rows), encoding='utf-8')
    print(len(rows), 'entries')


if __name__ == '__main__':
    main()
